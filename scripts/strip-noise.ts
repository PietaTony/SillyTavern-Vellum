/**
 * 剝掉註解與字串字面量，讓「原始碼裡有沒有出現某個寫法」這類檢查不會被文字誤導。
 *
 * 🔴 **獨立成一支的理由**：閘門腳本的主程式會在 import 時執行，
 * 別的地方想借用它的函式就會順便觸發一次檢查輸出。**共用的東西不要放在會自己跑的檔案裡。**
 * 刻意簡單：寧可多剝，不可少剝。
 */
export function stripNoise(src: string): string {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[^:])\/\/[^\n]*/g, '$1 ')
    .replace(/`(?:\\.|[^`\\])*`/g, '``')
    .replace(/'(?:\\.|[^'\\\n])*'/g, "''")
    .replace(/"(?:\\.|[^"\\\n])*"/g, '""');
}
